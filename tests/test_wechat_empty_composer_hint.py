"""Only the same-frame native gray-hint proof excludes one exact OCR row."""
import copy
import json
from pathlib import Path
import unittest

from test_chat_workflows import WeChatFake, bounds
from test_wechat_clear_outcome import ClearOutcomeFake
from chat_workflows import ChatSession, WECHAT, execute_chat
from desktop_observation import _chat_semantics


# Generated fake window/rows, never imported live observations.
SCENE = WeChatFake().visual({})
_seed_session = ChatSession({"app": WECHAT, "action": "read"}, lambda _: None)
_seed_session.frame = copy.deepcopy(SCENE["window_frame"])
COMPOSER = _seed_session.wechat_regions()["composer"]
VOICE_ROW = {"text": "按住鼠标 语音输入文字", "bounds": bounds(COMPOSER["x"] + 20, COMPOSER["y"] + 20, 140, 16)}
SCENE["ocr"].append(copy.deepcopy(VOICE_ROW))
SCENE["ocr_regions"] = [copy.deepcopy(COMPOSER)]
SCENE["captured_regions"] = [copy.deepcopy(SCENE["window_frame"])]


def hint_proof(value, row=VOICE_ROW):
    # The row/geometry is generated by the fake. This simulates the agreed
    # native51 proof shape; live gray-pixel verification belongs to native/root.
    return {"verified": True, "kind": "wechat_voice_placeholder", "text": row["text"],
            "bounds": copy.deepcopy(row["bounds"]), "snapshot_id": value["snapshot_id"],
            "frame_complete_serial": value["frame_complete_serial"], "composer_region": copy.deepcopy(COMPOSER),
            "verification_source": "same_frame_OCR_geometry_and_gray_glyph_pixels",
            "style": "light_gray_on_light_background"}


class GrayClearFake(ClearOutcomeFake):
    def __init__(self, proven=True, extra=None):
        super().__init__()
        self.proven, self.extra = proven, extra

    def visual(self, request, region_only=False):
        value = super().visual(request, region_only)
        if self.failed:
            value["ocr"].append(copy.deepcopy(VOICE_ROW))
            value["frame_complete_serial"] = len(self.calls)
            if self.proven:
                value["empty_composer_hint"] = hint_proof(value)
            if self.extra:
                value["ocr"].append({"text": self.extra, "bounds": bounds(COMPOSER["x"] + 3, COMPOSER["y"] + 45, 15, 16)})
        return value


class EmptyHintTests(unittest.TestCase):
    def session(self):
        session = ChatSession({"app": WECHAT, "action": "read"}, lambda _: self.fail("No native calls"))
        session.frame = copy.deepcopy(SCENE["window_frame"])
        return session

    def scene(self):
        value = copy.deepcopy(SCENE)
        value["frame_complete_serial"] = 41
        value["empty_composer_hint"] = hint_proof(value)
        return value

    def test_actual_gray_hint_proof_is_shared_by_draft_and_background_semantics(self):
        value = self.scene()
        self.assertEqual(self.session().wechat_draft(value), "")
        self.assertEqual(self.session().wechat_composer_rows(value), [])
        result = _chat_semantics(WECHAT, {"window_title": "微信"}, value)
        self.assertTrue(result["composer"]["value_complete"])
        self.assertEqual(result["composer"]["draft"], "")

    def test_same_phrase_without_native_proof_and_generic_placeholder_are_preserved(self):
        for text in (VOICE_ROW["text"], "按住鼠标语音输入文字", "输入文字", "输入消息", "自定义灰色提示"):
            value = self.scene()
            value.pop("empty_composer_hint")
            value["ocr"] = [{"text": text, "bounds": copy.deepcopy(VOICE_ROW["bounds"])}]
            self.assertEqual(self.session().wechat_draft(value), text)

    def test_literal_voice_phrase_is_user_content_when_drafted_and_owned_cleared(self):
        fake = WeChatFake()
        drafted = execute_chat({"app": WECHAT, "action": "draft", "text": VOICE_ROW["text"]}, fake, recipe_store=False)
        self.assertTrue(drafted["ok"], drafted)
        self.assertEqual(drafted["result"]["draft"], VOICE_ROW["text"])
        self.assertFalse(drafted["result"]["draft_empty"])
        cleared = execute_chat({"app": WECHAT, "action": "clear", "expected_draft": VOICE_ROW["text"]}, fake, recipe_store=False)
        self.assertTrue(cleared["ok"], cleared)
        self.assertEqual([call["key"] for call in fake.calls if call["command"] == "visual_key"], ["clear_draft"])

    def test_unproven_existing_voice_line_blocks_overwrite_without_input(self):
        fake = WeChatFake()
        fake.draft = VOICE_ROW["text"]
        result = execute_chat({"app": WECHAT, "action": "draft", "text": "不覆盖"}, fake, recipe_store=False)
        self.assertEqual(result["error"]["code"], "draft_present", result)
        self.assertEqual(fake.draft, VOICE_ROW["text"])
        self.assertFalse(any(call["command"] in {"visual_click", "visual_type_text", "visual_key", "batch"} for call in fake.calls))

    def test_black_malformed_or_stale_proof_never_strips_actual_text(self):
        cases = [("verified", False), ("kind", "generic_placeholder"), ("style", "black_text"),
                 ("verification_source", "string_only"), ("snapshot_id", "old-snapshot"),
                 ("frame_complete_serial", 40), ("frame_complete_serial", 41.0), ("text", "输入消息"),
                 ("bounds", {**VOICE_ROW["bounds"], "x": VOICE_ROW["bounds"]["x"] + 1}),
                 ("composer_region", bounds(50, 50, 100, 100))]
        for key, replacement in cases:
            with self.subTest(key=key, replacement=replacement):
                value = self.scene()
                value["empty_composer_hint"][key] = replacement
                self.assertEqual(self.session().wechat_draft(value), VOICE_ROW["text"])

    def test_proof_excludes_only_one_unique_exact_raw_row_and_keeps_unknown_caret(self):
        for extra in ("I", "|", "正文", "输入消息"):
            value = self.scene()
            value["ocr"].append({"text": extra, "bounds": bounds(COMPOSER["x"] + 3, COMPOSER["y"] + 45, 20, 16)})
            self.assertEqual(self.session().wechat_draft(value), extra)
        value = self.scene()
        value["ocr"].append(copy.deepcopy(VOICE_ROW))
        self.assertEqual(self.session().wechat_draft(value), VOICE_ROW["text"] + "\n" + VOICE_ROW["text"])
        value = self.scene()
        value["ocr"][-1]["text"] = "按住鼠标语音输入文字"
        self.assertEqual(self.session().wechat_draft(value), "按住鼠标语音输入文字")

    def test_clear_final_outcome_accepts_gray_hint_proof_without_replaying_delete(self):
        fake = GrayClearFake()
        result = execute_chat({"app": WECHAT, "action": "clear", "expected_draft": fake.draft}, fake, recipe_store=False)
        self.assertTrue(result["ok"], result)
        self.assertTrue(result["result"]["draft_empty"])
        self.assertTrue(result["clear_recovery"]["verified"])
        self.assertEqual(result["clear_recovery"]["original_error_code"], "postcondition_failed")
        self.assertEqual(sum(call["command"] == "visual_key" for call in fake.calls), 1)

    def test_clear_final_outcome_refuses_unproven_same_text_or_unknown_caret(self):
        for proven, extra in ((False, None), (True, "I"), (True, "输入消息")):
            fake = GrayClearFake(proven, extra)
            result = execute_chat({"app": WECHAT, "action": "clear", "expected_draft": fake.draft}, fake, recipe_store=False)
            self.assertEqual(result["error"]["code"], "postcondition_failed", result)
            self.assertFalse(result["clear_recovery"]["verified"])
            self.assertFalse(result["focus_restore_attempted"])
            self.assertEqual(sum(call["command"] == "visual_key" for call in fake.calls), 1)


if __name__ == "__main__":
    unittest.main()
